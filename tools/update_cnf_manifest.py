#!/usr/bin/env python3
"""Rebuild or check corpus metadata against the generators and pinned SATLIB."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys

# Keep running the maintenance tool from leaving private caches in tools/.
sys.dont_write_bytecode = True

from check_cnf_corpus import CORPUS, parse_dimacs
from fetch_satlib_cnf import collect
from generate_edge_cnf import fixtures as edge_fixtures
from generate_structured_cnf import fixtures as structured_fixtures


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without rewriting the manifest.")
    parser.add_argument("--offline", action="store_true", help="Require cached SATLIB archives.")
    args = parser.parse_args()
    edges = edge_fixtures()
    structured = structured_fixtures()
    # Check generated bytes as well as parsing them: metadata must describe the
    # current generator output, rather than arbitrary edits to fixture files.
    for fixture in edges:
        if (CORPUS / "edge" / f"{fixture.name}.cnf").read_bytes() != fixture.content():
            raise SystemExit(f"Edge fixture differs from generator: {fixture.name}")
    for fixture in structured:
        if (CORPUS / "structured" / f"{fixture.name}.cnf").read_bytes() != fixture.dimacs().encode("ascii"):
            raise SystemExit(f"Structured fixture differs from generator: {fixture.name}")
    entries = [fixture.metadata() for fixture in edges + structured]
    entries += collect(check=True, offline=args.offline)
    for entry in entries:
        data = (CORPUS / entry["path"]).read_bytes()
        variables, clauses = parse_dimacs(data)
        entry.update(variables=variables, clauses=len(clauses),
                     sha256=hashlib.sha256(data).hexdigest())
    manifest = {
        "schema_version": 1,
        "format": "DIMACS CNF",
        "instances": sorted(entries, key=lambda entry: entry["path"]),
    }
    data = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
    target = CORPUS / "manifest.json"
    if args.check:
        if target.read_bytes() != data:
            raise SystemExit("Manifest differs from reproducible corpus metadata.")
    else:
        target.write_bytes(data)
    print(f"{'Verified' if args.check else 'Wrote'} manifest for {len(entries)} CNF fixtures.")


if __name__ == "__main__":
    main()
